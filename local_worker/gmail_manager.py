import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from dotenv import load_dotenv

load_dotenv()

class GmailManager:
    def __init__(self, index):
        self.email_address = os.getenv(f"GMAIL_USER{index}")
        self.app_password = os.getenv(f"GMAIL_PASS{index}")
        self.smtp_server = "smtp.gmail.com"
        self.smtp_port = 465

    def send_outreach(self, to_email, subject, body, thread_id=None, last_msg_id=None):
        msg = MIMEMultipart()
        msg['From'] = self.email_address
        msg['To'] = to_email
        msg['Subject'] = subject

        if thread_id and last_msg_id:
            msg['In-Reply-To'] = last_msg_id
            msg['References'] = last_msg_id
            if not subject.lower().startswith("re:"):
                msg['Subject'] = "Re: " + subject

        msg.attach(MIMEText(body, 'html'))

        try:
            with smtplib.SMTP_SSL(self.smtp_server, self.smtp_port) as server:
                server.login(self.email_address, self.app_password)
                server.send_message(msg)
                
                # Get the actual Message-ID generated by the server
                # (Simple fallback if not returned: msg['Message-ID'])
                sent_msg_id = msg['Message-ID']
                return True, thread_id or sent_msg_id, sent_msg_id
        except Exception as e:
            print(f"❌ Failed to send email via {self.email_address}: {e}")
            return False, None, None
